import { describe, expect, it } from 'vitest';
import { parseFutures, parseMargin } from '../../../scripts/lib/marketRisk';

const stocks = Array.from({ length: 120 }, (_, i) => [String(1100 + i), `股票${i}`, '1', '2', '0', '100', i === 0 ? '1,500' : '10', '0', '5', '1', '0', '20', '30', '0', '']);

describe('大盤風險資料解析', () => {
  it('融資融券：新版 tables 格式，第一個「今日餘額」是融資', () => {
    const j = {
      stat: 'OK',
      tables: [
        {
          title: '信用交易統計',
          fields: ['項目', '買進', '賣出', '現金(券)償還', '前日餘額', '今日餘額'],
          data: [
            ['融資(交易單位)', '1', '1', '1', '7,000,000', '7,100,000'],
            ['融券(交易單位)', '1', '1', '1', '200,000', '210,000'],
            ['融資金額(仟元)', '1', '1', '1', '300,000,000', '310,000,000'],
          ],
        },
        {
          title: '融資融券彙總',
          fields: ['代號', '名稱', '買進', '賣出', '現金償還', '前日餘額', '今日餘額', '次一營業日限額', '買進', '賣出', '現券償還', '前日餘額', '今日餘額', '次一營業日限額', '資券互抵'],
          data: stocks,
        },
      ],
    };
    const m = parseMargin(j)!;
    expect(m.finAmt).toBe(310_000_000);
    expect(m.finLots).toBe(7_100_000);
    expect(m.shortLots).toBe(210_000);
    expect(m.perStock['1100']).toBe(1500);
    expect(m.perStock['1101']).toBe(10);
  });

  it('沒有資料（休市）回傳 null', () => {
    expect(parseMargin({ stat: '很抱歉，沒有符合條件的資料!' })).toBeNull();
  });

  it('期貨：外資的大台＋小台÷4', () => {
    const csv = [
      '日期,商品名稱,身份別,多方交易口數,多方交易契約金額(千元),空方交易口數,空方交易契約金額(千元),多空交易口數淨額,多空交易契約金額淨額(千元),多方未平倉口數,多方未平倉契約金額(千元),空方未平倉口數,空方未平倉契約金額(千元),多空未平倉口數淨額,多空未平倉契約金額淨額(千元)',
      '2025/06/02,臺股期貨,自營商,1,1,1,1,0,0,1,1,1,1,500,1',
      '2025/06/02,臺股期貨,外資及陸資,1,1,1,1,0,0,1,1,1,1,-20000,1',
      '2025/06/02,小型臺指期貨,外資及陸資,1,1,1,1,0,0,1,1,1,1,-4000,1',
      '2025/06/02,電子期貨,外資及陸資,1,1,1,1,0,0,1,1,1,1,-999,1',
    ].join('\r\n');
    expect(parseFutures(csv)).toEqual({ '2025-06-02': -21000 });
  });
});
