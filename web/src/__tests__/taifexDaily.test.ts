import { describe, expect, it } from 'vitest';
import { parseTxDaily } from '../../../scripts/lib/taifexDaily';

const csv = `交易日期,契約,到期月份(週別),開盤價,最高價,最低價,收盤價,漲跌價,漲跌%,成交量,結算價,未沖銷契約數,最後最佳買價,最後最佳賣價,歷史最高價,歷史最低價,是否因訊息面暫停交易,交易時段,價差對單式委託成交量
2026/11/18,TX,202611,40700,40800,40100,40200,-500,-1.2%,90000,40200,80000,40190,40200,46000,20000,,一般,
2026/11/18,TX,202612,40750,40850,40150,40250,-500,-1.2%,9000,40250,8000,40240,40250,46000,20000,,一般,
2026/11/18,TX,202611W4,40700,40800,40100,40200,-500,-1.2%,1000,-,-,-,-,-,-,,一般,
2026/11/18,TX,202611/202612,-,-,-,-,-,-,10,-,-,-,-,-,-,,一般,
2026/11/18,TX,202611,40210,40500,40000,40480,280,0.7%,30000,-,-,40470,40480,46000,20000,,盤後,
2026/11/18,MTX,202611,40700,40800,40100,40200,-500,-1.2%,90000,40200,80000,40190,40200,46000,20000,,一般,`;

describe('parseTxDaily', () => {
  it('臺股期貨近月：一般時段與夜盤分開，不含週契約、價差、小台', () => {
    const d = parseTxDaily(csv);
    expect(d['2026-11-18'].d).toEqual([40700, 40800, 40100, 40200, 90000]);
    expect(d['2026-11-18'].n).toEqual([40210, 40500, 40000, 40480, 30000]);
  });
  it('欄位不符時報錯', () => {
    expect(() => parseTxDaily('日期,商品\n1,2')).toThrow();
  });
});
